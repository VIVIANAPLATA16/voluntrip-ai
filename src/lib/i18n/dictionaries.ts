export type TranslationKey = keyof typeof dictionaries.en;

export function t(
  locale: Locale,
  key: TranslationKey,
  params?: Record<string, string | number>
): string {
  let text: string = dictionaries[locale][key] ?? dictionaries.en[key] ?? key;
  if (params) {
    for (const [paramKey, value] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${paramKey}\\}`, "g"), String(value));
    }
  }
  return text;
}

/** Map browser language to supported locale (fallback: en). */
export function detectBrowserLocale(): Locale {
  if (typeof navigator === "undefined") return "en";
  const lang = navigator.language.toLowerCase();
  if (lang.startsWith("es")) return "es";
  if (lang.startsWith("pt")) return "pt";
  if (lang.startsWith("en")) return "en";
  return "en";
}

export function localeLanguageName(locale: Locale): string {
  if (locale === "es") return "español";
  if (locale === "pt") return "português";
  return "English";
}

