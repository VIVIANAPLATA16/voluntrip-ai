import type { CurrencyCode } from "@/types";
import rawCountries from "./data/destinations-countries.json";
import {
  getPopularCountries,
  searchAllDestinationCountries,
} from "./destination-regions";

export type { DestinationTab, DestinationRegion } from "./destination-regions";
export {
  DESTINATION_TABS,
  TOP_VOLUNTEER_COUNTRY_CODES,
  getCountriesByTab,
  getPopularCountries,
} from "./destination-regions";

export interface Destination {
  city: string;
  country: string;
  countryCode: string;
  flag: string;
  localCurrency: CurrencyCode;
  popular?: boolean;
}

export interface DestinationCountry {
  country: string;
  code: string;
  flag: string;
  localCurrency: CurrencyCode;
  cities: string[];
  popular: boolean;
  region: "americas" | "europe" | "asia-oceania" | "africa-me";
}

/** ISO country code → flag emoji */
export function flagFromCode(countryCode: string): string {
  const code = countryCode.toUpperCase();
  if (code.length !== 2) return "🌍";
  return String.fromCodePoint(
    ...[...code].map((c) => 0x1f1e6 - 65 + c.charCodeAt(0))
  );
}

/** Generated by scripts/build-destinations.js (country-state-city + volunteer hubs) */
export const DESTINATION_COUNTRIES: DestinationCountry[] =
  rawCountries as DestinationCountry[];

/** Flat list derived from country hierarchy (for legacy consumers) */
export const DESTINATIONS: Destination[] = DESTINATION_COUNTRIES.flatMap((c) =>
  c.cities.map((city) => ({
    city,
    country: c.country,
    countryCode: c.code,
    flag: c.flag,
    localCurrency: c.localCurrency,
    popular: c.popular,
  }))
);

export const COUNTRY_COUNT = DESTINATION_COUNTRIES.length;

/** @deprecated Use getCountriesByTab or searchAllDestinationCountries */
export function searchDestinationCountries(
  query: string
): {
  countries: DestinationCountry[];
  autoExpandCode: string | null;
  matchedCity: string | null;
} {
  const q = query.toLowerCase().trim();
  if (!q) {
    return {
      countries: getPopularCountries(DESTINATION_COUNTRIES),
      autoExpandCode: null,
      matchedCity: null,
    };
  }
  return searchAllDestinationCountries(query, DESTINATION_COUNTRIES);
}

/** @deprecated Prefer searchAllDestinationCountries */
export function searchDestinations(query: string): Destination[] {
  const { countries } = searchAllDestinationCountries(
    query,
    DESTINATION_COUNTRIES
  );
  return countries.flatMap((c) =>
    c.cities.map((city) => ({
      city,
      country: c.country,
      countryCode: c.code,
      flag: c.flag,
      localCurrency: c.localCurrency,
      popular: c.popular,
    }))
  );
}

export { searchAllDestinationCountries };
